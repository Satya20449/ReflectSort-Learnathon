@dataclass
class SensorSimulatorConfig:
    """
    Configuration parameters for the optical sensor simulation.
    """
    adc_resolution_bits: int = DEFAULT_ADC_RESOLUTION_BITS
    min_adc_value: float = 0.0
    max_adc_value: float = DEFAULT_MAX_ADC_COUNT  # 12-bit ADC = 4095.0
    default_angle_deg: float = 45.0
    default_led_setting: str = "WHITE_100PCT"
    default_sample_position: str = "tray_center"
    noise_std_dev: float = 12.0                   # Simulated Gaussian sensor noise (in ADC counts)
    random_seed: Optional[int] = None

    def validate(self) -> None:
        if self.adc_resolution_bits <= 0 or self.adc_resolution_bits > 24:
            raise ValidationError(f"Invalid adc_resolution_bits {self.adc_resolution_bits}. Must be in [1, 24].")
        if self.min_adc_value < 0 or self.max_adc_value <= self.min_adc_value:
            raise ValidationError(
                f"Invalid ADC limits: min={self.min_adc_value}, max={self.max_adc_value}"
            )
        if self.noise_std_dev < 0:
            raise ValidationError(f"noise_std_dev must be non-negative, got {self.noise_std_dev}")


class SensorSimulator:
    """
    Software simulator for the ReflectSort optical sensing assembly.
    Provides reproducible, seedable synthetic measurement records.
    """

    def __init__(self, config: Optional[SensorSimulatorConfig] = None) -> None:
        self.config = config or SensorSimulatorConfig()
        self.config.validate()
        self._rng = random.Random()
        if self.config.random_seed is not None:
            self.set_seed(self.config.random_seed)

    def set_seed(self, seed: int) -> None:
        """Set fixed random seed for fully deterministic, reproducible test runs."""
        self._rng.seed(seed)

    def _clamp_adc(self, val: float) -> float:
        """Clamp ADC counts within configured hardware range [min_adc, max_adc]."""
        return max(self.config.min_adc_value, min(self.config.max_adc_value, val))

    def generate_reading(
        self,
        specimen_id: str,
        run_id: str,
        profile_name: str = "MEDIUM_GRAIN",
        sample_position: Optional[str] = None,
        angle_deg: Optional[float] = None,
        led_setting: Optional[str] = None,
        ambient_offset: float = 0.0,
        custom_noise_std: Optional[float] = None,
        timestamp: Optional[str] = None,
    ) -> SensorRecord:
        """
        Generate a single synthetic SensorRecord.

        Args:
            specimen_id: Identifier for the test item (e.g. "SEED-0042")
            run_id: Identifier for the testing batch or run (e.g. "RUN-2026-A")
            profile_name: Name of demonstration profile fixture
            sample_position: Mechanical tray location label
            angle_deg: Illumination / reflection angle in degrees
            led_setting: LED operating mode string
            ambient_offset: Configurable offset to simulate fluctuating ambient light
            custom_noise_std: Override default noise standard deviation
            timestamp: Optional ISO 8601 string; if omitted, current UTC time is used.
        """
        profile = DEMO_FIXTURE_PROFILES.get(
            profile_name,
            SyntheticShadeProfile(
                profile_name=profile_name,
                nominal_sample_adc=2000.0,
                nominal_ambient_adc=850.0,
                nominal_reference_adc=2400.0,
                description=f"Custom/ad-hoc profile fixture '{profile_name}'",
            ),
        )

        std_dev = custom_noise_std if custom_noise_std is not None else self.config.noise_std_dev
        noise_sample = self._rng.gauss(0.0, std_dev) if std_dev > 0 else 0.0
        noise_amb = self._rng.gauss(0.0, std_dev * 0.5) if std_dev > 0 else 0.0
        noise_ref = self._rng.gauss(0.0, std_dev * 0.3) if std_dev > 0 else 0.0

        raw_sample = self._clamp_adc(profile.nominal_sample_adc + noise_sample + ambient_offset * 0.2)
        raw_ambient = self._clamp_adc(profile.nominal_ambient_adc + noise_amb + ambient_offset)
        raw_ref = self._clamp_adc(profile.nominal_reference_adc + noise_ref)

        pos = sample_position or self.config.default_sample_position
        angle = angle_deg if angle_deg is not None else self.config.default_angle_deg
        led = led_setting or self.config.default_led_setting
        ts = timestamp or datetime.now(timezone.utc).isoformat()

        record = SensorRecord(
            specimen_id=specimen_id,
            run_id=run_id,
            sample_LDR=round(raw_sample, 2),
            ambient_LDR=round(raw_ambient, 2),
            reference_value=round(raw_ref, 2),
            sample_position=pos,
            angle=angle,
            LED_setting=led,
            timestamp=ts,
            data_source="simulated",
        )
        record.compute_standard_derived_features()
        return record

    def generate_batch(
        self,
        count: int,
        run_id: str,
        specimen_prefix: str = "SEED",
        profile_distribution: Optional[List[str]] = None,
        custom_noise_std: Optional[float] = None,
    ) -> List[SensorRecord]:
        """
        Generate a batch of multiple synthetic SensorRecords.

        Args:
            count: Number of records to generate (must be >= 1)
            run_id: Batch run identifier
            specimen_prefix: Prefix for specimen IDs (e.g. "SEED" -> "SEED-0001")
            profile_distribution: List of profiles to sample from; defaults to standard demo set
            custom_noise_std: Optional noise override
        """
        if count <= 0:
            raise ValidationError(f"Batch count must be >= 1, got {count}")

        profiles = profile_distribution or ["LIGHT_GRAIN", "MEDIUM_GRAIN", "DARK_GRAIN"]
        records: List[SensorRecord] = []

        for i in range(1, count + 1):
            spec_id = f"{specimen_prefix}-{i:04d}"
            selected_profile = self._rng.choice(profiles)
            rec = self.generate_reading(
                specimen_id=spec_id,
                run_id=run_id,
                profile_name=selected_profile,
                custom_noise_std=custom_noise_std,
            )
            records.append(rec)

        return records
